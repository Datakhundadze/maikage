// Generates supabase/functions/meta-webhook/catalogSnapshot.ts from the site's
// own catalog (src/lib/catalog.ts and friends).
//
// WHY A SNAPSHOT. Lovable deploys only the function folder, so the meta-webhook
// edge function cannot import from src/ at deploy time. The DM sketch renderer
// needs the same product photos, placement zones, colours, brands, text palette
// and style labels the website uses; this script copies them into a plain data
// module inside the function folder.
//
// KEEPING IT IN SYNC. src/test/socialSketch.test.ts rebuilds the source with
// buildSnapshotSource() and compares it byte for byte with the committed file,
// so a catalog change without a re-run fails the test suite. To regenerate:
//
//   npx vite-node scripts/gen-social-catalog-snapshot.ts
//
// (vite-node, not node/tsx: catalog.ts imports through the "@/" alias, which
// vite-node resolves from vite.config.ts.)
//
// URLS. Relative catalog paths ("/products/…") are made absolute with
// SITE_ORIGIN (https://maika.ge, where Lovable serves public/). Absolute
// storage URLs are kept as they are. The PNG original is used, never the .webp
// swap findImageForColor does in a browser: the server-side decoder reads PNG.

import { writeFileSync } from "node:fs";
import path from "node:path";
import {
  catalog,
  PRODUCTS,
  SUB_PRODUCTS,
  COLORS,
  FRONT_ONLY_PRODUCTS,
  type CatalogEntry,
} from "../src/lib/catalog";
import { TEXT_COLORS } from "../src/lib/textColors";
import { getStyleOptions } from "../src/lib/designStyles";
import { MAX_SEED_PROMPT_LENGTH, MAX_SEED_TEXT_LENGTH } from "../src/lib/constructorSeed";

export const SITE_ORIGIN = "https://maika.ge";

export const SNAPSHOT_PATH = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  "../supabase/functions/meta-webhook/catalogSnapshot.ts",
);

export function absoluteUrl(url: string | null): string | null {
  if (!url) return null;
  if (/^https?:\/\//i.test(url)) return url;
  return `${SITE_ORIGIN}${url.startsWith("/") ? "" : "/"}${url}`;
}

/** Every catalog entry, in generation order, via the public lookup API. */
function allEntries(): CatalogEntry[] {
  const out: CatalogEntry[] = [];
  for (const p of PRODUCTS) {
    const subs = catalog.getSubProducts(p.type);
    for (const sub of subs.length > 0 ? subs : [p.type]) {
      for (const color of catalog.getAvailableColors(p.type, sub)) {
        for (const view of ["front", "back"] as const) {
          const e = catalog.findProduct(p.type, sub, color, view);
          if (e) out.push(e);
        }
      }
    }
  }
  return out;
}

const j = (v: unknown) => JSON.stringify(v);

export function buildSnapshotSource(): string {
  const lines: string[] = [];
  lines.push(
    "// GENERATED by scripts/gen-social-catalog-snapshot.ts from src/lib/catalog.ts,",
    "// src/lib/textColors.ts, src/lib/designStyles.ts and src/lib/constructorSeed.ts.",
    "// Do not edit by hand: run `npx vite-node scripts/gen-social-catalog-snapshot.ts`.",
    "// src/test/socialSketch.test.ts fails when this file is out of date.",
    "",
    "export interface SnapshotZone { x: number; y: number; scale: number; scaleY?: number }",
    "export interface SnapshotEntry {",
    "  type: string;",
    "  sub: string;",
    "  color: string;",
    "  view: \"front\" | \"back\";",
    "  /** Absolute public PNG URL, or null when the catalog has no photo for it. */",
    "  url: string | null;",
    "  zone: SnapshotZone;",
    "}",
    "",
    `export const SITE_ORIGIN = ${j(SITE_ORIGIN)};`,
    `export const MAX_SEED_TEXT_LENGTH = ${MAX_SEED_TEXT_LENGTH};`,
    `export const MAX_SEED_PROMPT_LENGTH = ${MAX_SEED_PROMPT_LENGTH};`,
    "",
    `export const PRODUCT_TYPES: string[] = ${j(PRODUCTS.map((p) => p.type))};`,
    "",
    "export const SUB_PRODUCTS: Record<string, string[]> = {",
    ...Object.entries(SUB_PRODUCTS).map(([k, v]) => `  ${j(k)}: ${j(v)},`),
    "};",
    "",
    `export const FRONT_ONLY_PRODUCTS: string[] = ${j([...FRONT_ONLY_PRODUCTS])};`,
    "",
    "export const COLORS: { name: string; hex: string }[] = [",
    ...COLORS.map((c) => `  ${j({ name: c.name, hex: c.hex })},`),
    "];",
    "",
    "export const TEXT_COLORS: { name: string; hex: string }[] = [",
    ...TEXT_COLORS.map((c) => `  ${j({ name: c.name, hex: c.hex })},`),
    "];",
    "",
    "/** The AI style chips, index-parallel (en[i] and ge[i] are the same style). */",
    `export const STYLE_OPTIONS = { en: ${j(getStyleOptions("en"))}, ge: ${j(getStyleOptions("ge"))} };`,
    "",
    "export const ENTRIES: SnapshotEntry[] = [",
    ...allEntries().map((e) => {
      const zone: Record<string, number> = { x: e.placementZone.x, y: e.placementZone.y, scale: e.placementZone.scale };
      if (e.placementZone.scaleY !== undefined) zone.scaleY = e.placementZone.scaleY;
      return `  ${j({ type: e.type, sub: e.subType, color: e.color, view: e.view, url: absoluteUrl(e.imageUrl), zone })},`;
    }),
    "];",
    "",
  );
  return lines.join("\n");
}

// Run directly (vite-node) → write the file.
// vitest imports this module too (and sets VITEST); only a direct run writes.
// vite-node removes the script path from process.argv, so argv cannot tell.
if (!process.env.VITEST) {
  writeFileSync(SNAPSHOT_PATH, buildSnapshotSource());
  console.log(`wrote ${SNAPSHOT_PATH}`);
}
