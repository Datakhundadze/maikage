/** The cameraman's yaw (°) at forward time t — shortest-way interpolation between samples. */
export function personYawAt(t: number): number {
  const f = Math.min(PERSON_YAW.length - 1, Math.max(0, t / PERSON_YAW_STEP));
  const i = Math.min(PERSON_YAW.length - 2, Math.floor(f));
  const a = PERSON_YAW[i];
  const d = ((((PERSON_YAW[i + 1] - a) % 360) + 540) % 360) - 180;
  return ((((a + d * (f - i)) % 360) + 540) % 360) - 180;
}
